"""Write docs/data_summary.md from the downloaded ToolPrivBench data.

Usage:
    uv run python scripts/data_summary.py [--out docs/data_summary.md]

Every number in the output is computed from the data, never typed by hand. The script also
checks the counts against the dataset's own published `metadata/stats.json` and exits non-zero
if any differ.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from privilege_drift.data import (
    check_against_published,
    load_role_tier_map,
    load_toolprivbench,
    render_markdown,
    summarise,
)

RAW_DIR = Path("data/raw/toolprivbench")
HEADER = """# Data summary

Generated by `scripts/data_summary.py` (`make data-summary`). Do not edit by hand.

Source: ToolPrivBench, BAAI/ToolPrivBench (CC-BY-4.0), Yang et al., arXiv 2606.20023, revision
a86a3e8. Tier map: `configs/tiers/toolprivbench_tiers.yaml` (decision D18): `standard` tools are
tier `user`, `risk` tools are tier `admin`.

"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--out", type=Path, default=Path("docs/data_summary.md"))
    args = parser.parse_args()

    tier_map = load_role_tier_map()
    scenarios = load_toolprivbench(RAW_DIR / "data/benchmark.jsonl", tier_map)
    published = json.loads((RAW_DIR / "metadata/stats.json").read_text())

    problems = check_against_published(scenarios, published, tier_map)
    status = (
        "All counts match the dataset's published `metadata/stats.json`."
        if not problems
        else "MISMATCH with the published statistics:\n\n" + "\n".join(f"- {p}" for p in problems)
    )
    args.out.write_text(HEADER + render_markdown(summarise(scenarios)) + "\n" + status + "\n")
    print(f"wrote {args.out}")
    for p in problems:
        print(f"MISMATCH {p}", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
