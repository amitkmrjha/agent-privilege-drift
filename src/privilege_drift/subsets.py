"""Frozen experiment inputs: the stratified scenario subset and the seed schedule.

Everything here is a pure function of ``MASTER_SEED`` and the data, so the committed files in
``prereg/`` can be regenerated byte for byte and checked (``make subsets-check``).

No random-number library is used. Each choice ranks items by SHA-256 of ``(master seed, label,
item)`` and takes the lowest ranks. That behaves like a random draw, never depends on file order
or on a library version, and is easy to describe in the thesis.
"""

from __future__ import annotations

import hashlib
import json
import re
from collections import Counter
from collections.abc import Mapping, Sequence
from typing import Any

from pydantic import BaseModel, ConfigDict, model_validator

from privilege_drift.schema import Scenario

# Arbitrary but fixed: the date this was frozen. Changing it changes every file below.
MASTER_SEED = 20261119
SUBSET_SIZE = 50
SEEDS_PER_SCENARIO = 5  # the grid uses 3; storing 5 makes the 3-to-5 contingency a config change
N_CELLS = 27  # 3 models x 3 failure rates x 3 mediators (cells 0 to 17 are the exp-v1 grid)
SEED_LIMIT = 2**31 - 1  # Ollama seeds are signed 32-bit integers

METHOD = (
    "per-domain quota (equal, with the remainder going to the domains ranked first by "
    "sha256(master_seed, 'extra', domain)); within a domain, the scenarios ranked first by "
    "sha256(master_seed, 'pick', domain, scenario_id)"
)


def _rank(*parts: object) -> int:
    text = "\x1f".join(str(p) for p in parts)
    return int.from_bytes(hashlib.sha256(text.encode()).digest()[:16], "big")


# --- Scenario subset -------------------------------------------------------------------------


def stratum_sizes(domains: Sequence[str], total: int, master_seed: int) -> dict[str, int]:
    """How many scenarios each domain contributes: ``total`` split as evenly as possible.

    With 50 scenarios over 8 domains that is six domains with 6 and two with 7. Which two get
    the extra one is decided by the hash ranking, not by hand.
    """
    if not domains:
        raise ValueError("no domains to stratify over")
    if total < len(domains):
        raise ValueError(f"cannot take {total} scenarios from {len(domains)} domains")
    base, extra = divmod(total, len(domains))
    ranked = sorted(domains, key=lambda d: (_rank(master_seed, "extra", d), d))
    bumped = set(ranked[:extra])
    return {d: base + (d in bumped) for d in sorted(domains)}


def select_stratified(
    ids_by_domain: Mapping[str, Sequence[str]], total: int, master_seed: int
) -> dict[str, list[str]]:
    """Pick the subset: ``{domain: sorted scenario ids}``."""
    sizes = stratum_sizes(list(ids_by_domain), total, master_seed)
    chosen: dict[str, list[str]] = {}
    for domain, size in sizes.items():
        ids = sorted(set(ids_by_domain[domain]))
        if len(ids) < size:
            raise ValueError(f"domain {domain!r} has {len(ids)} scenarios, need {size}")
        ranked = sorted(ids, key=lambda i: (_rank(master_seed, "pick", domain, i), i))
        chosen[domain] = sorted(ranked[:size])
    return chosen


class _Frozen(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


class Subset(_Frozen):
    """The frozen scenario subset, tied to the exact data it was drawn from."""

    source: str
    dataset_revision: str
    data_sha256: str
    master_seed: int
    method: str
    size: int
    domains: dict[str, str]  # scenario id -> domain

    @model_validator(mode="after")
    def _check_stratification(self) -> Subset:
        if len(self.domains) != self.size:
            raise ValueError(f"subset has {len(self.domains)} scenarios, expected {self.size}")
        counts = self.counts()
        low, extra = divmod(self.size, len(counts))
        high = low + 1 if extra else low
        bad = {d: n for d, n in counts.items() if n not in (low, high)}
        if bad:
            raise ValueError(f"domains outside the {low}-{high} quota: {bad}")
        if extra and sum(1 for n in counts.values() if n == high) != extra:
            raise ValueError(f"exactly {extra} domains must have {high} scenarios")
        return self

    @property
    def scenario_ids(self) -> tuple[str, ...]:
        return tuple(sorted(self.domains))

    def counts(self) -> dict[str, int]:
        return dict(sorted(Counter(self.domains.values()).items()))


def build_subset(
    scenarios: Sequence[Scenario],
    *,
    source: str,
    dataset_revision: str,
    data_sha256: str,
    total: int = SUBSET_SIZE,
    master_seed: int = MASTER_SEED,
) -> Subset:
    ids_by_domain: dict[str, list[str]] = {}
    for s in scenarios:
        ids_by_domain.setdefault(s.domain, []).append(s.id)
    chosen = select_stratified(ids_by_domain, total, master_seed)
    return Subset(
        source=source,
        dataset_revision=dataset_revision,
        data_sha256=data_sha256,
        master_seed=master_seed,
        method=METHOD,
        size=total,
        domains={sid: domain for domain, ids in chosen.items() for sid in ids},
    )


# --- Seed schedule ---------------------------------------------------------------------------


def make_seed_pool(master_seed: int, n: int) -> list[int]:
    """``n`` distinct seeds in ``[0, SEED_LIMIT)``. The first ``k`` of a longer pool equal a
    pool of size ``k``, so growing the subset never reshuffles earlier seeds."""
    pool: list[int] = []
    seen: set[int] = set()
    counter = 0
    while len(pool) < n:
        value = _rank(master_seed, "seed", counter) % SEED_LIMIT
        counter += 1
        if value not in seen:
            seen.add(value)
            pool.append(value)
    return pool


class SeedSchedule(_Frozen):
    """Which seeds each scenario gets in each cell (decision D10).

    One master pool holds a distinct seed for every (scenario, seed index). Each cell deals the
    whole pool out again in its own permuted order, so within a cell no seed repeats, while a
    scenario's seeds differ between cells. ``cells[c][scenario_id]`` has ``seeds_per_scenario``
    seeds; a 3-seed grid uses the first 3.
    """

    master_seed: int
    seeds_per_scenario: int
    scenario_ids: tuple[str, ...]
    pool: tuple[int, ...]
    cells: tuple[dict[str, tuple[int, ...]], ...]

    @model_validator(mode="after")
    def _check(self) -> SeedSchedule:
        k = self.seeds_per_scenario
        if list(self.scenario_ids) != sorted(set(self.scenario_ids)):
            raise ValueError("scenario_ids must be unique and sorted")
        if len(self.pool) != len(self.scenario_ids) * k or len(set(self.pool)) != len(self.pool):
            raise ValueError("pool must hold one distinct seed per scenario and seed index")
        if not all(0 <= s < SEED_LIMIT for s in self.pool):
            raise ValueError("seed outside the allowed range")
        for index, cell in enumerate(self.cells):
            if set(cell) != set(self.scenario_ids):
                raise ValueError(f"cell {index}: scenarios differ from scenario_ids")
            if any(len(seeds) != k for seeds in cell.values()):
                raise ValueError(f"cell {index}: every scenario needs exactly {k} seeds")
            flat = [s for seeds in cell.values() for s in seeds]
            if len(set(flat)) != len(flat) or set(flat) != set(self.pool):
                raise ValueError(f"cell {index}: seeds repeat or do not cover the pool")
        return self

    def seeds_for(self, cell: int, scenario_id: str, n: int | None = None) -> tuple[int, ...]:
        """The first ``n`` seeds (default all) for a scenario in a cell."""
        seeds = self.cells[cell][scenario_id]
        return seeds if n is None else seeds[:n]


def _permuted(pool: Sequence[int], master_seed: int, cell: int) -> list[int]:
    """The pool in this cell's own order (ranked by hash, so independent of library versions)."""
    order = sorted(range(len(pool)), key=lambda i: (_rank(master_seed, "cell", cell, i), i))
    return [pool[i] for i in order]


def build_seed_schedule(
    scenario_ids: Sequence[str],
    *,
    n_cells: int = N_CELLS,
    seeds_per_scenario: int = SEEDS_PER_SCENARIO,
    master_seed: int = MASTER_SEED,
) -> SeedSchedule:
    ids = tuple(sorted(set(scenario_ids)))
    pool = make_seed_pool(master_seed, len(ids) * seeds_per_scenario)
    cells: list[dict[str, tuple[int, ...]]] = []
    for cell in range(n_cells):
        dealt = _permuted(pool, master_seed, cell)
        cells.append(
            {
                sid: tuple(dealt[j * seeds_per_scenario : (j + 1) * seeds_per_scenario])
                for j, sid in enumerate(ids)
            }
        )
    return SeedSchedule(
        master_seed=master_seed,
        seeds_per_scenario=seeds_per_scenario,
        scenario_ids=ids,
        pool=tuple(pool),
        cells=tuple(cells),
    )


# --- Files and hashes ------------------------------------------------------------------------

_INT_LIST = re.compile(r"\[\s*(-?\d[\d,\s-]*?)\s*\]")


def to_canonical_json(model: BaseModel) -> str:
    """Stable text for a model: sorted keys, 2-space indent, integer lists on one line."""
    data: Any = model.model_dump(mode="json")
    text = json.dumps(data, sort_keys=True, indent=2)
    text = _INT_LIST.sub(lambda m: "[" + re.sub(r"\s+", " ", m.group(1)) + "]", text)
    return text + "\n"


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def hashes_text(files: Mapping[str, str]) -> str:
    """``shasum -a 256`` format for ``{path: content}``, so ``shasum -c`` can verify it."""
    return "".join(f"{sha256_text(content)}  {path}\n" for path, content in sorted(files.items()))
